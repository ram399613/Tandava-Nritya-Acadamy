export async function GET(req) {
  try {
    const { searchParams } = new URL(req.url);
    const category = searchParams.get('category');
    const level = searchParams.get('level');
    const search = searchParams.get('search');

    let conn = null;
    try {
      conn = await dbConnect();
    } catch (_) {}

    if (conn && isDbConnected()) {
      try {
        const query = { isActive: true };
        if (category && category !== 'All') query.category = new RegExp(category, 'i');
        if (level && level !== 'All') query.level = new RegExp(level, 'i');
        if (search) {
          query.$or = [
            { name: { $regex: search, $options: 'i' } },
            { title: { $regex: search, $options: 'i' } },
            { description: { $regex: search, $options: 'i' } },
          ];
        }

        const courses = await Course.find(query).sort({ createdAt: -1 });
        if (courses && courses.length > 0) {
          const formatted = courses.map((c) => {
            const doc = c.toObject ? c.toObject() : c;
            return {
              ...doc,
              title: doc.title || doc.name,
              name: doc.title || doc.name,
              photo: doc.photo || SEED_COURSES[0].photo,
              icon: doc.icon || '🩰',
            };
          });
          return NextResponse.json({
            success: true,
            count: formatted.length,
            courses: formatted,
            data: formatted,
          });
        }
      } catch (dbErr) {
        console.warn('DB course query failed, returning comprehensive catalog:', dbErr.message);
      }
    }

    let filtered = SEED_COURSES;
    if (category && category !== 'All') {
      const catLower = category.toLowerCase();
      filtered = filtered.filter((c) => c.category.toLowerCase().includes(catLower));
    }
    if (level && level !== 'All') {
      const lvlLower = level.toLowerCase();
      filtered = filtered.filter((c) => c.level.toLowerCase().includes(lvlLower));
    }
    if (search) {
      const q = search.toLowerCase();
      filtered = filtered.filter(
        (c) =>
          c.title.toLowerCase().includes(q) ||
          c.description.toLowerCase().includes(q) ||
          c.category.toLowerCase().includes(q)
      );
    }

    return NextResponse.json({
      success: true,
      count: filtered.length,
      courses: filtered,
      data: filtered,
    });
  } catch (error) {
    return NextResponse.json({ success: false, message: error.message }, { status: 500 });
  }
}

export async function POST(req) {
  try {
    const authUser = await getAuthUser(req);
    const body = await req.json();

    const newCourse = {
      _id: 'crs_' + Date.now(),
      title: body.title,
      name: body.title,
      category: body.category || 'Hip-Hop',
      level: body.level || 'Beginner',
      icon: '🩰',
      photo: body.photo || 'https://images.unsplash.com/photo-1508700115892-45ecd05ae2ad?q=80&w=800&auto=format&fit=crop',
      description: body.description || 'Master performance choreography with top faculty.',
      fee: Number(body.fee) || 4500,
      durationWeeks: Number(body.durationWeeks) || 12,
      capacity: Number(body.maxCapacity) || 20,
      maxCapacity: Number(body.maxCapacity) || 20,
      enrolledCount: 0,
      studioRoom: body.studioRoom || 'Studio 1 (Grand Hall)',
      scheduleDays: Array.isArray(body.scheduleDays) ? body.scheduleDays : ['Monday', 'Wednesday'],
      scheduleTime: body.scheduleTime || '18:00 - 19:30',
      isActive: true,
      createdAt: new Date().toISOString(),
    };

    SEED_COURSES.unshift(newCourse);

    return NextResponse.json({
      success: true,
      message: 'Course created successfully',
      course: newCourse,
      data: newCourse,
    });
  } catch (error) {
    return NextResponse.json({ success: false, message: error.message }, { status: 400 });
  }
}
